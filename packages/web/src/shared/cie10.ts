export function searchCie10(q: string, limit = 12): { code: string; name: string }[] {
  const s = q.trim().toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
  if (!s) return CIE10.slice(0, limit).map(([code, name]) => ({ code, name }));
  return CIE10.filter(([c, n]) => {
    const nn = n.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
    return c.toLowerCase().startsWith(s) || nn.includes(s);
  })
    .slice(0, limit)
    .map(([code, name]) => ({ code, name }));
}
